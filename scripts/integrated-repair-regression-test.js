'use strict';
const assert=require('node:assert/strict');
const {statementCoverage,balanceMetadata}=require('../services/statementCoverage');
const {paymentState,paymentSql}=require('../services/expensePaymentDomain');
const {expenseFilters}=require('../services/expenseRegisterFilters');
const { _ingestion:imports }=require('../controllers/statementImportController');
async function main(){
  const bill={total_amount:'100.00',status:'unpaid',due_date:null};
  assert.equal(paymentState(bill,'0.00',0,'2026-10-07').balanceDue,'100.00');
  assert.equal(paymentState(bill,'25.25',1,'2026-10-07').balanceDue,'74.75');
  assert.equal(paymentState(bill,'100.00',1,'2026-10-07').status,'paid');
  assert.equal(paymentState(bill,'105.00',1,'2026-10-07').overpayment,'5.00');
  assert.notEqual(paymentState(bill,'0.00',0,'2026-10-07').status,'overdue');
  assert.equal(paymentState({...bill,due_date:'2026-10-06'},'25.25',1,'2026-10-07').status,'overdue');
  assert.match(paymentSql().join,/voided_at IS NULL/);
  const filter=expenseFilters({fy:'2026',category:'Very long category',status:'overdue'});
  assert.deepEqual(filter.params,['2026-07-01','2027-06-30','Very long category']);
  assert.match(filter.where,/e.due_date IS NOT NULL/);
  assert.throws(()=>expenseFilters({from:'2026-10-07',to:'2026-09-01'}),/precede/);
  const coverage=statementCoverage([{statement_start_date:'2026-01-01',statement_end_date:'2026-01-31'},{statement_start_date:'2026-01-20',statement_end_date:'2026-02-28'},{statement_start_date:'2026-04-01',statement_end_date:'2026-04-30'}]);
  assert.deepEqual(coverage.statement_gaps,[{from:'2026-03-01',to:'2026-03-31'}]);
  assert.match(statementCoverage([]).coverage_label,/unverified/);
  assert.equal(balanceMetadata({connection_type:'MANUAL',available_balance:'50.00',current_ledger_balance:'20.00'}).profile_balance,'20.00');
  assert.equal(balanceMetadata({connection_type:'OPEN_BANKING',connection_status:'CONNECTED',last_synced_at:'2026-10-07',available_balance:'50.00'}).balance_basis,'LIVE_AVAILABLE');
  const row={transaction_date:'2026-09-01',description:'Repeated payment',debit:'42.50',credit:'0',currency:'AUD'};
  const hash=imports.statementRowHash(7,row);
  const database={query:async(sql)=>sql.includes('SELECT row_hash,')?[[{row_hash:hash,source_content_hash:'original-a'}]]:[[]]};
  const overlap=await imports.normalizeAndDedupe(database,{id:7,currency:'AUD'},[row],{contentHash:'original-b'});
  assert.equal(overlap.normalized[0].validation_status,'WARNING');
  assert.equal(overlap.normalized[0].selected,0);
  assert.equal(overlap.normalized[0].duplicate_status,'POSSIBLE_DUPLICATE');
  assert.notEqual(overlap.normalized[0].row_hash,hash,'a reviewer may preserve a legitimate separate payment without colliding with the existing row');
  const sameFile=await imports.normalizeAndDedupe(database,{id:7,currency:'AUD'},[row],{contentHash:'original-a'});
  assert.equal(sameFile.normalized[0].validation_status,'DUPLICATE');
  const repeated=await imports.normalizeAndDedupe({query:async()=>[[]]},{id:7,currency:'AUD'},[row,row],{contentHash:'new-file'});
  assert.equal(repeated.counts.valid,2);
  assert.notEqual(repeated.normalized[0].row_hash,repeated.normalized[1].row_hash);
  assert.equal(imports.normalizeRow(7,'AUD',{...row,currency:'INR'},1).validation_status,'REJECTED');
  assert.equal(imports.normalizeRow(7,'AUD',{...row,description:'Total debits'},1).validation_status,'REJECTED');
  assert.notEqual(imports.semanticTransactionKey(7,{...row,reference:'BankUnique001',running_balance:'10.00'}),imports.semanticTransactionKey(7,{...row,reference:'BankUnique001',running_balance:'20.00'}));
  console.log('Integrated repair behaviour passed: exact payables, real statement gaps, balance basis, conservative overlap review, repeats, summaries and currency isolation.');
}
main().then(()=>require('../config/db').end()).catch(error=>{console.error(error);process.exitCode=1;require('../config/db').end();});
